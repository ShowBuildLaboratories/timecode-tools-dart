// Regenerates lib/src/ffi/bindings.g.dart from native/include/timecode_tools.h.
//
//   dart run tool/ffigen.dart
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  bool ours(String name) =>
      name.startsWith('tt_') || name.startsWith('Tt') || name.startsWith('TT_');
  await FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('native/include/timecode_tools.h')],
    ),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/ffi/bindings.g.dart')),
      preamble:
          '// Generated by tool/ffigen.dart from '
          'native/include/timecode_tools.h. Do not edit.\n'
          '// ignore_for_file: type=lint, unused_field',
      style: const NativeExternalBindings(
        assetId: 'package:timecode_tools/src/ffi/bindings.g.dart',
      ),
    ),
    visitors: [
      Visitor(
        func: (node) {
          if (!ours(node.originalName)) return;
          node.isIncluded = true;
          // Getters and arithmetic do not call back into Dart.
          node.isLeaf = true;
          if (node.originalName.endsWith('_free')) {
            node.exposeSymbolAddress = true;
          }
        },
        struct: (node) {
          if (ours(node.originalName)) node.isIncluded = true;
        },
        macroConstant: (node) {
          if (ours(node.originalName)) node.isIncluded = true;
        },
      ),
    ],
  ).generate();
}
